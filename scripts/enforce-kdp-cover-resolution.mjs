import { readFile, writeFile } from "node:fs/promises";

const path = "supabase/functions/enqueue-export-bundle/index.ts";
let source = await readFile(path, "utf8");

function replaceOnce(needle, replacement, label) {
  const first = source.indexOf(needle);
  if (first < 0) throw new Error(`${label}: pattern not found`);
  if (source.indexOf(needle, first + needle.length) >= 0) throw new Error(`${label}: pattern not unique`);
  source = source.slice(0, first) + replacement + source.slice(first + needle.length);
}

replaceOnce(
  'import { buildKdpPrintCoverPdf, getPdfPageCount, type KdpPaperType, type KdpTrimSize } from "../_shared/kdp-print-cover.ts";\n',
  'import { buildKdpPrintCoverPdf, getPdfPageCount, type KdpPaperType, type KdpTrimSize } from "../_shared/kdp-print-cover.ts";\nimport { requireKdpFrontCoverResolution, type KdpCoverResolutionAssessment } from "../_shared/kdp-cover-resolution.ts";\n',
  'resolution import',
);

replaceOnce(
  '    let kdpPrintCover: Awaited<ReturnType<typeof buildKdpPrintCoverPdf>> | null = null;\n    let kdpSourcePageCount: number | null = null;\n',
  '    let kdpPrintCover: Awaited<ReturnType<typeof buildKdpPrintCoverPdf>> | null = null;\n    let kdpSourcePageCount: number | null = null;\n    let kdpCoverResolution: KdpCoverResolutionAssessment | null = null;\n',
  'resolution state',
);

replaceOnce(
  '      if (!supportedTrims.has(requestedTrim)) throw new Error("INVALID_KDP_TRIM_SIZE");\n\n      const supportedPaper',
  '      if (!supportedTrims.has(requestedTrim)) throw new Error("INVALID_KDP_TRIM_SIZE");\n      kdpCoverResolution = requireKdpFrontCoverResolution(cover.widthPx, cover.heightPx, requestedTrim);\n\n      const supportedPaper',
  'resolution gate',
);

replaceOnce(
  '          spine_width_in: kdpPrintCover.geometry.spineWidthIn,\n          barcode_mode: barcodeMode,',
  '          spine_width_in: kdpPrintCover.geometry.spineWidthIn,\n          cover_effective_dpi: kdpCoverResolution.effectiveDpi,\n          barcode_mode: barcodeMode,',
  'timer resolution metadata',
);

replaceOnce(
  '          total_height_in: kdpPrintCover.geometry.totalHeightIn,\n          barcode_mode: kdpPrintCover.barcodeMode,',
  '          total_height_in: kdpPrintCover.geometry.totalHeightIn,\n          cover_resolution: kdpCoverResolution,\n          barcode_mode: kdpPrintCover.barcodeMode,',
  'export resolution metadata',
);

if (!source.includes('KDP_COVER_RESOLUTION')) {
  // Error strings are generated by the shared helper; import/call is the invariant.
  if (!source.includes('requireKdpFrontCoverResolution')) throw new Error('resolution gate missing');
}
await writeFile(path, source);
console.log('KDP 300-DPI resolution gate integrated.');
